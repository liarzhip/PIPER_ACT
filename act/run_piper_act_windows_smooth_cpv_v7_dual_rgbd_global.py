class RealSenseCamera:
    """Background RealSense RGB-D capture aligned to the color stream."""

    def __init__(
        self,
        width=640,
        height=480,
        fps=30,
        depth_min_mm=250.0,
        depth_max_mm=3000.0,
        serial="",
    ):
        try:
            import pyrealsense2 as rs
        except ImportError as exc:
            raise RuntimeError(
                "pyrealsense2 is not installed. Run: pip install pyrealsense2"
            ) from exc

        self.rs = rs
        self.width = int(width)
        self.height = int(height)
        self.fps = int(fps)
        self.depth_min_mm = float(depth_min_mm)
        self.depth_max_mm = float(depth_max_mm)
        self.serial = str(serial).strip()

        self.pipeline = rs.pipeline()
        self.config = rs.config()

        if self.serial:
            self.config.enable_device(self.serial)

        self.config.enable_stream(
            rs.stream.depth,
            self.width,
            self.height,
            rs.format.z16,
            self.fps,
        )
        self.config.enable_stream(
            rs.stream.color,
            self.width,
            self.height,
            rs.format.bgr8,
            self.fps,
        )

        self.profile = self.pipeline.start(self.config)
        device = self.profile.get_device()

        try:
            self.device_name = device.get_info(rs.camera_info.name)
        except Exception:
            self.device_name = "RealSense"

        try:
            self.device_serial = device.get_info(rs.camera_info.serial_number)
        except Exception:
            self.device_serial = self.serial or "unknown"

        depth_sensor = device.first_depth_sensor()
        self.depth_scale_m = float(depth_sensor.get_depth_scale())
        self.align = rs.align(rs.stream.color)

        self.lock = threading.Lock()
        self.latest_rgb = None
        self.latest_depth_mm = None
        self.latest_stamp = 0.0
        self.running = True

        self.thread = threading.Thread(
            target=self._capture_loop,
            daemon=True,
            name="realsense_external_rgbd",
        )
        self.thread.start()

        print(
            f"[OK] RealSense started: {self.device_name} "
            f"serial={self.device_serial} | "
            f"{self.width}x{self.height}@{self.fps}"
        )

    def _capture_loop(self):
        while self.running:
            try:
                frames = self.pipeline.wait_for_frames(1000)
                aligned = self.align.process(frames)

                depth_frame = aligned.get_depth_frame()
                color_frame = aligned.get_color_frame()
                if not depth_frame or not color_frame:
                    continue

                bgr = np.asanyarray(color_frame.get_data())
                rgb = cv2.cvtColor(bgr, cv2.COLOR_BGR2RGB)

                raw_depth = np.asanyarray(
                    depth_frame.get_data()
                ).astype(np.float32)
                depth_mm = (
                    raw_depth
                    * self.depth_scale_m
                    * 1000.0
                )

                valid = (
                    np.isfinite(depth_mm)
                    & (depth_mm >= self.depth_min_mm)
                    & (depth_mm <= self.depth_max_mm)
                )

                depth_u16 = np.zeros(
                    depth_mm.shape,
                    dtype=np.uint16,
                )
                depth_u16[valid] = np.rint(
                    depth_mm[valid]
                ).astype(np.uint16)

                if depth_u16.shape != rgb.shape[:2]:
                    raise RuntimeError(
                        "RealSense aligned RGB/depth mismatch: "
                        f"rgb={rgb.shape[:2]}, depth={depth_u16.shape}"
                    )

                stamp = time.monotonic()

                with self.lock:
                    self.latest_rgb = np.ascontiguousarray(
                        rgb,
                        dtype=np.uint8,
                    )
                    self.latest_depth_mm = depth_u16
                    self.latest_stamp = stamp

            except Exception as exc:
                if self.running:
                    print(f"[WARN] RealSense frame error: {exc}")
                time.sleep(0.02)

    def wait_ready(self, timeout_s=10.0):
        deadline = time.monotonic() + float(timeout_s)
        while time.monotonic() < deadline:
            pack = self.get_latest()
            if pack is not None:
                rgb, depth, _ = pack
                valid = (
                    float(np.count_nonzero(depth))
                    / float(depth.size)
                )
                print(
                    f"[OK] RealSense ready: "
                    f"{rgb.shape[1]}x{rgb.shape[0]} | "
                    f"depth_valid={valid*100.0:.1f}%"
                )
                return
            time.sleep(0.05)

        raise TimeoutError(
            "RealSense did not provide RGB-D frames. "
            "Check RealSense Viewer, USB 3.x and pyrealsense2."
        )

    def get_latest(self):
        with self.lock:
            if (
                self.latest_rgb is None
                or self.latest_depth_mm is None
            ):
                return None
            return (
                self.latest_rgb.copy(),
                self.latest_depth_mm.copy(),
                float(self.latest_stamp),
            )

    def close(self):
        self.running = False
        if self.thread is not None:
            self.thread.join(timeout=1.0)
        try:
            self.pipeline.stop()
        except Exception:
            pass


