# Temporal aggregation (ACT temporal ensembling)
# ============================================================
class TemporalAggregator:
    """
    时间集成，用于在实时控制中对ACT模型的输出进行平滑处理。它维护一个固定大小的缓冲区，
    存储最近的动作预测，并根据时间衰减权重对这些预测进行加权平均，以生成当前时刻的动作输出。
    """
    def __init__(self, chunk_size, k=0.01):
        self.chunk_size = int(chunk_size)
        self.k = float(k)
        self.buffer = deque()

    def clear(self):
        """
        清空缓冲区，丢弃以前所有存储的动作预测。
        :return:
        """
        self.buffer.clear()

    def add(self, start_t, chunk):
        """
        将新的动作预测块添加到缓冲区，并根据时间窗口丢弃过期的预测。
        :param start_t:
        :param chunk:
        :return:
        """
        self.buffer.append((int(start_t), chunk.copy()))

        while self.buffer:
            old_start, _ = self.buffer[0]
            if int(start_t) - old_start >= self.chunk_size:
                self.buffer.popleft() # 如果当前片段起始位置与上一个片段起始位置相差超过chunk_size，则丢弃过期的预测
            else:
                break

    def current(self, t):
        """
        根据当前时间t，从缓冲区中获取所有有效的动作预测，并根据时间衰减权重进行加权平均，生成当前时刻的动作输出。
        :param t:
        :return: 当前的融合动作预测
        """
        candidates = []

        for start_t, chunk in self.buffer:
            index = int(t) - start_t
            if 0 <= index < chunk.shape[0]:
                candidates.append(chunk[index])

        if not candidates:
            raise RuntimeError("No temporal-aggregation candidate for current step.")

        actions = np.stack(candidates, axis=0)
        weights = np.exp(
            -self.k * np.arange(len(actions), dtype=np.float32)
        )
        weights /= weights.sum()

        return np.sum(actions * weights[:, None], axis=0).astype(np.float32)


