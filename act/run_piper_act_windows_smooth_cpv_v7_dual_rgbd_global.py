FIRMWARE_MAP = {
    "default": PiperFW.DEFAULT,
    "v183": PiperFW.V183,
    "v188": PiperFW.V188,
    "v189": PiperFW.V189,
} # 需要调用对应的固件。


class PiperXRobot:
    def __init__(
        self,
        channel="0",
        firmware="auto",
        startup_timeout=10.0,
        gripper_force=1.0,
    ):
        self.channel = str(channel)
        self.gripper_force = float(gripper_force)
        self.robot = None
        self.gripper = None
        # Serialize CAN API access between ACT inference and the CPV servo thread.
        self.io_lock = threading.RLock()

        if firmware == "auto":
            fw = self._detect_firmware(startup_timeout)
        else:
            fw = FIRMWARE_MAP[firmware]

        self._connect(fw) # 连接对应的固件
        self._wait_feedback(startup_timeout)

    def _make_config(self, fw):
        """
        创建机械臂的配置，包括指定型号，固件配置，接口类型和通道号。
        :param fw:
        :return:
        """
        return create_agx_arm_config(
            robot=ArmModel.PIPER_X,
            firmeware_version=fw,
            interface="agx_cando",
            channel=self.channel,
        )

    def _detect_firmware(self, timeout_s):
        """
        自动检测固件版本
        :param timeout_s:
        :return:
        """
        print(
            f"[INFO] Opening agx_cando channel={self.channel} "
            "to detect PiPER-X firmware..."
        )

        probe = AgxArmFactory.create_arm(self._make_config(PiperFW.DEFAULT))
        probe.connect()

        deadline = time.monotonic() + float(timeout_s)
        info = None

        try:
            while time.monotonic() < deadline:
                try:
                    info = probe.get_firmware(timeout=0.5, min_interval=0.1)
                except TypeError:
                    info = probe.get_firmware()

                if info is not None:
                    break
                time.sleep(0.05)
        finally:
            probe.disconnect()

        if info is None:
            raise TimeoutError(
                "Unable to detect PiPER firmware. Use --firmware "
                "default/v183/v188/v189 explicitly."
            )

        software_version = str(info["software_version"])
        fw = resolve_firmware_profile(ArmModel.PIPER_X, software_version)
        print(f"[OK] Firmware {software_version} -> SDK profile {fw}")
        return fw

    def _connect(self, fw):
        """
        正式连接机械臂，初始化夹爪，并打印连接成功信息。
        :param fw:
        :return:
        """
        config = self._make_config(fw)
        self.robot = AgxArmFactory.create_arm(config)

        # pyAgxArm recommends creating the effector before connect().
        self.gripper = self.robot.init_effector(
            self.robot.OPTIONS.EFFECTOR.AGX_GRIPPER
        )

        self.robot.connect()
        print(
            f"[OK] PiPER-X connected: interface=agx_cando "
            f"channel={self.channel}"
        )

    def _wait_feedback(self, timeout_s):
        """
        等待机械臂和夹爪的反馈，确保它们已经准备好。
        :param timeout_s:
        :return:
        """
        print("[INFO] Waiting for joint + gripper feedback...")
        deadline = time.monotonic() + float(timeout_s)

        while time.monotonic() < deadline:
            if self.get_qpos(require_width_mode=False) is not None:
                print("[OK] PiPER-X feedback ready.")
                return
            time.sleep(0.05)

        raise TimeoutError(
            "PiPER-X feedback not ready. Check robot power, CAN channel, "
            "agx_cando and gripper feedback."
        )

    def get_qpos(self, require_width_mode=True):
        """获取机械臂 6 轴角度(rad) + 夹爪宽度(m)。"""
        with self.io_lock:
            joint_fb = self.robot.get_joint_angles()
            gripper_fb = self.gripper.get_gripper_status()

            if joint_fb is None or gripper_fb is None:
                return None

            joints = np.asarray(joint_fb.msg, dtype=np.float32).reshape(-1)
            if joints.size != 6:
                return None

            mode = getattr(gripper_fb.msg, "mode", None)
            if require_width_mode and mode is not None and mode != "width":
                raise RuntimeError(
                    f"Gripper feedback mode={mode!r}. "
                    "ACT dataset_stand_bottle expects width in meters."
                )

            gripper_m = float(gripper_fb.msg.value)
            qpos = np.concatenate(
                [joints, np.asarray([gripper_m], dtype=np.float32)]
            ).astype(np.float32)

            if not np.all(np.isfinite(qpos)):
                return None

            return qpos

    def get_joint_hz(self):
        """获取机械臂关节反馈频率。"""
        with self.io_lock:
            msg = self.robot.get_joint_angles()
            if msg is None:
                return 0.0
            return float(getattr(msg, "hz", 0.0))

    def _print_cpv_cv(self, title="CPV CV"):
        """读取并打印 1~6 轴当前 CPV 速度参数。"""
        print(f"[INFO] {title}:")
        values = []
        for joint_index in range(1, 7):
            try:
                value = self.robot.get_cpv_cv(joint_index)
                values.append(value)
                print(f"       J{joint_index}: {value}")
            except Exception as exc:
                values.append(None)
                print(f"       J{joint_index}: read failed ({exc})")
        return values

    def configure_cpv_speed(self, cpv_cv):
        """
        一次性配置 1~6 轴的 CPV CV 参数。

        官方 pyAgxArm CPV 示例使用 set_cpv_cv(joint_index, value)
        配置各轴 CPV 速度参数。这里仅在启动 CONTROL 时设置一次，
        绝不会放进实时控制循环中重复写入。
        """
        cpv_cv = float(cpv_cv)
        if cpv_cv <= 0:
            raise ValueError("cpv_cv must be > 0")

        self._print_cpv_cv("CPV CV before configuration")

        print(f"[INFO] Setting CPV CV for J1~J6 -> {cpv_cv}")
        for joint_index in range(1, 7):
            result = self.robot.set_cpv_cv(joint_index, cpv_cv)
            print(f"       J{joint_index}: set result={result}")

        # Give the controller a short moment, then read back for confirmation.
        time.sleep(0.10)
        self._print_cpv_cv("CPV CV after configuration")

    def enable_control(
        self,
        speed_percent=20,
        cpv_cv=0.20,
        configure_cpv_cv=True,
        timeout_s=5.0,
    ):
        """
        启用机械臂并切换到 CPV 连续位置模式。

        保留 ACT / Temporal Aggregation / EMA / Deadband / Rate Limit。
        V2 新增：启动 CONTROL 时可一次性配置 1~6 轴 CPV CV 参数。
        """
        if hasattr(self.robot, "set_joint_limits_enabled"):
            self.robot.set_joint_limits_enabled(True)

        if hasattr(self.robot, "set_auto_set_motion_mode_enabled"):
            self.robot.set_auto_set_motion_mode_enabled(False)

        deadline = time.monotonic() + float(timeout_s)
        while time.monotonic() < deadline:
            if self.robot.enable():
                break
            time.sleep(0.02)
        else:
            raise TimeoutError("Unable to enable all PiPER-X joints.")

        # 保留原来的全局速度百分比设置。
        self.robot.set_speed_percent(int(speed_percent))

        self.robot.set_motion_mode(
            self.robot.OPTIONS.MOTION_MODE.CPV
        )

        if configure_cpv_cv:
            self.configure_cpv_speed(cpv_cv)
        else:
            self._print_cpv_cv("CPV CV (kept unchanged)")

        print(
            f"[OK] Robot enabled | MOVE_CPV | "
            f"speed_percent={int(speed_percent)}% | "
            f"cpv_cv={float(cpv_cv):.3f} | "
            f"configured={bool(configure_cpv_cv)}"
        )

    def send_action(self, action):
        """CPV position streaming: 6 轴位置(rad) + 夹爪宽度(m)。"""
        action = np.asarray(action, dtype=np.float32).reshape(7)
        if not np.all(np.isfinite(action)):
            raise RuntimeError("Refusing to send non-finite CPV action.")

        with self.io_lock:
            for joint_index in range(1, 7):
                self.robot.move_cpv_pos(
                    joint_index=joint_index,
                    pos=float(action[joint_index - 1]),
                )

            self.gripper.move_gripper_m(
                value=float(action[6]),
                force=self.gripper_force,
            )

    def hold_current(self):
        """
        结束控制时，发送当前关节角度和夹爪状态作为动作命令，保持机械臂在当前位置。
        :return:
        """
        qpos = self.get_qpos(require_width_mode=False)
        if qpos is None:
            return
        try:
            self.send_action(qpos)
        except Exception:
            pass

    def get_arm_status_code(self):
        """获取机械臂状态码。"""
        with self.io_lock:
            status = self.robot.get_arm_status()
            if status is None:
                return None

            value = getattr(status.msg, "arm_status", None)
            if value is None:
                return None

            try:
                return int(value)
            except Exception:
                return None

    def emergency_stop(self):
        """触发电子急停。"""
        try:
            with self.io_lock:
                self.robot.electronic_emergency_stop()
        except Exception:
            pass

    def close(self):
        """
        关闭机械臂连接，释放资源。
        :return:
        """
        if self.robot is not None:
            try:
                self.robot.disconnect()
            except Exception:
                pass


