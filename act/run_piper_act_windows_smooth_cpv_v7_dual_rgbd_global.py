def draw_preview(
    rgb,
    mode,
    started,
    step,
    inference_ms,
    loop_hz,
    qpos_hz,
    image_age_ms,
    action,
    max_qpos_z,
):
    """
    生成相机窗口的画面
    :param rgb:
    :param mode:
    :param started:
    :param step:
    :param inference_ms:
    :param loop_hz:
    :param qpos_hz:
    :param image_age_ms:
    :param action:
    :param max_qpos_z:
    :return:
    """
    frame = cv2.cvtColor(rgb, cv2.COLOR_RGB2BGR)
    cv2.rectangle(frame, (0, 0), (frame.shape[1], 112), (0, 0, 0), -1)

    state = "RUNNING" if started else "READY"
    help_text = "Q/ESC=stop" if started else "S=start | Q/ESC=quit"

    cv2.putText(
        frame,
        f"{mode} | {state} | {help_text}",
        (12, 25),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.55,
        (0, 0, 255) if mode == "CONTROL" else (0, 255, 255),
        2,
        cv2.LINE_AA,
    )

    cv2.putText(
        frame,
        (
            f"step={step} infer={inference_ms:.1f}ms "
            f"servo={loop_hz:.1f}Hz qpos={qpos_hz:.0f}Hz "
            f"image={image_age_ms:.0f}ms zmax={max_qpos_z:.1f}"
        ),
        (12, 53),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.42,
        (255, 255, 255),
        1,
        cv2.LINE_AA,
    )

    if action is not None:
        deg = np.rad2deg(action[:6])
        text = (
            "target(deg)="
            + ",".join(f"{x:.1f}" for x in deg)
            + f" grip={action[6] * 1000:.1f}mm"
        )
        cv2.putText(
            frame,
            text,
            (12, 80),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.38,
            (255, 255, 255),
            1,
            cv2.LINE_AA,
        )

    return frame



def draw_dual_preview(
    wrist_rgb,
    external_rgb,
    mode,
    started,
    step,
    inference_ms,
    loop_hz,
    qpos_hz,
    wrist_age_ms,
    external_age_ms,
    sync_delta_ms,
    action,
    max_qpos_z,
):
    wrist = draw_preview(
        rgb=wrist_rgb,
        mode=mode,
        started=started,
        step=step,
        inference_ms=inference_ms,
        loop_hz=loop_hz,
        qpos_hz=qpos_hz,
        image_age_ms=wrist_age_ms,
        action=action,
        max_qpos_z=max_qpos_z,
    )
    external = draw_preview(
        rgb=external_rgb,
        mode=mode,
        started=started,
        step=step,
        inference_ms=inference_ms,
        loop_hz=loop_hz,
        qpos_hz=qpos_hz,
        image_age_ms=external_age_ms,
        action=action,
        max_qpos_z=max_qpos_z,
    )

    cv2.putText(
        wrist,
        "WRIST / ORBBEC",
        (12, 106),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.48,
        (255, 255, 255),
        1,
        cv2.LINE_AA,
    )
    cv2.putText(
        external,
        f"EXTERNAL / REALSENSE | sync={sync_delta_ms:.1f}ms",
        (12, 106),
        cv2.FONT_HERSHEY_SIMPLEX,
        0.48,
        (255, 255, 255),
        1,
        cv2.LINE_AA,
    )

    if external.shape[:2] != wrist.shape[:2]:
        external = cv2.resize(
            external,
            (
                wrist.shape[1],
                wrist.shape[0],
            ),
        )

    return np.hstack(
        [wrist, external]
    )


