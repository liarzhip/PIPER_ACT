class SmoothTrajectoryFilter:
    """
    将 ACT 的低频/不均匀目标转换成适合 CPV 连续发送的轨迹。

    处理顺序：
        ACT/Temporal Aggregation target
            -> EMA target smoothing
            -> joint velocity limit
            -> joint acceleration limit
            -> optional per-cycle hard step limit
            -> actual-qpos tracking guard
            -> gripper EMA + step limit

    默认不使用关节 deadband，避免“小变化被吃掉、积累后突然跳变”。
    """

    def __init__(
        self,
        joint_alpha=0.20,
        gripper_alpha=0.15,
        max_joint_vel_deg_s=15.0,
        max_joint_acc_deg_s2=60.0,
        max_joint_step_deg=1.0,
        max_tracking_error_deg=5.0,
        joint_deadband_deg=0.0,
        max_gripper_step_m=0.0100,
        gripper_deadband_m=0.0005,
        gripper_min_m=0.0,
        gripper_max_m=0.10,
    ):
        if not 0.0 < float(joint_alpha) <= 1.0:
            raise ValueError("joint_alpha must be in (0, 1].")
        if not 0.0 < float(gripper_alpha) <= 1.0:
            raise ValueError("gripper_alpha must be in (0, 1].")
        if max_joint_vel_deg_s <= 0 or max_joint_acc_deg_s2 <= 0:
            raise ValueError("joint velocity/acceleration limits must be > 0.")

        self.joint_alpha = float(joint_alpha)
        self.gripper_alpha = float(gripper_alpha)
        self.max_joint_vel = np.deg2rad(float(max_joint_vel_deg_s))
        self.max_joint_acc = np.deg2rad(float(max_joint_acc_deg_s2))
        self.max_joint_step = np.deg2rad(float(max_joint_step_deg))
        self.max_tracking_error = np.deg2rad(float(max_tracking_error_deg))
        self.joint_deadband = np.deg2rad(float(joint_deadband_deg))
        self.max_gripper_step = float(max_gripper_step_m)
        self.gripper_deadband = float(gripper_deadband_m)
        self.gripper_min = float(gripper_min_m)
        self.gripper_max = float(gripper_max_m)

        self.last_command = None
        self.last_velocity = np.zeros(6, dtype=np.float32)
        self.ema_target = None

    def reset(self, qpos):
        qpos = np.asarray(qpos, dtype=np.float32).reshape(7)
        self.last_command = qpos.copy()
        self.last_velocity[:] = 0.0
        self.ema_target = qpos.copy()
        self.last_command[6] = np.clip(
            self.last_command[6], self.gripper_min, self.gripper_max
        )

    def filter(self, target, actual_qpos, dt):
        target = np.asarray(target, dtype=np.float32).reshape(7)
        actual_qpos = np.asarray(actual_qpos, dtype=np.float32).reshape(7)
        if not np.all(np.isfinite(target)):
            raise RuntimeError("ACT produced NaN/Inf action values.")
        if not np.all(np.isfinite(actual_qpos)):
            raise RuntimeError("Robot qpos contains NaN/Inf values.")

        # 防止线程调度偶发抖动导致 dt 极端异常。
        dt = float(np.clip(dt, 0.005, 0.10))

        if self.last_command is None:
            self.reset(actual_qpos)

        previous = self.last_command.copy()

        # 1) EMA 作用于“目标”，不直接制造位置跳变。
        self.ema_target[:6] = (
            self.joint_alpha * target[:6]
            + (1.0 - self.joint_alpha) * self.ema_target[:6]
        )
        self.ema_target[6] = (
            self.gripper_alpha * target[6]
            + (1.0 - self.gripper_alpha) * self.ema_target[6]
        )

        # 2) 从位置误差得到期望速度，然后限制最大速度。
        vel_des = (self.ema_target[:6] - previous[:6]) / dt
        vel_des = np.clip(
            vel_des,
            -self.max_joint_vel,
            self.max_joint_vel,
        )

        # 可选极小 deadband；默认 0，等于关闭。
        if self.joint_deadband > 0:
            tiny = np.abs(self.ema_target[:6] - previous[:6]) < self.joint_deadband
            vel_des[tiny] = 0.0

        # 3) 限制加速度，即限制相邻控制周期的速度变化。
        max_dv = self.max_joint_acc * dt
        vel_cmd = np.clip(
            vel_des,
            self.last_velocity - max_dv,
            self.last_velocity + max_dv,
        )

        # 4) 积分得到新的位置命令。
        joint_cmd = previous[:6] + vel_cmd * dt

        # 额外硬步长保护；通常速度限制会更早起作用。
        joint_cmd = np.clip(
            joint_cmd,
            previous[:6] - self.max_joint_step,
            previous[:6] + self.max_joint_step,
        )

        # 5) 防止命令轨迹远远跑在真实机器人前面。
        joint_cmd = np.clip(
            joint_cmd,
            actual_qpos[:6] - self.max_tracking_error,
            actual_qpos[:6] + self.max_tracking_error,
        )

        # 如果 tracking guard 裁剪了位置，重新计算真实发送速度。
        vel_cmd = (joint_cmd - previous[:6]) / dt

        # 6) 夹爪仍保留 EMA + deadband + 单步限制。
        gripper_target = float(self.ema_target[6])
        if abs(gripper_target - float(previous[6])) < self.gripper_deadband:
            gripper_cmd = float(previous[6])
        else:
            gripper_cmd = float(np.clip(
                gripper_target,
                float(previous[6]) - self.max_gripper_step,
                float(previous[6]) + self.max_gripper_step,
            ))
        gripper_cmd = float(np.clip(
            gripper_cmd, self.gripper_min, self.gripper_max
        ))

        command = np.concatenate([
            joint_cmd.astype(np.float32),
            np.asarray([gripper_cmd], dtype=np.float32),
        ])

        self.last_command = command.astype(np.float32)
        self.last_velocity = vel_cmd.astype(np.float32)
        return self.last_command.copy(), self.last_velocity.copy()


class ServoSharedState:
    """ACT inference thread 与 CPV servo thread 之间的线程安全共享状态。"""

    def __init__(self):
        self.lock = threading.Lock()
        self.target = None
        self.target_stamp = 0.0
        self.command = None
        self.qpos = None
        self.velocity = np.zeros(6, dtype=np.float32)
        self.servo_hz = 0.0
        self.error = None

    def set_target(self, target):
        with self.lock:
            self.target = np.asarray(target, dtype=np.float32).copy()
            self.target_stamp = time.monotonic()

    def get_target(self):
        with self.lock:
            if self.target is None:
                return None, 0.0
            return self.target.copy(), float(self.target_stamp)

    def update_servo(self, command, qpos, velocity, servo_hz):
        with self.lock:
            self.command = np.asarray(command, dtype=np.float32).copy()
            self.qpos = np.asarray(qpos, dtype=np.float32).copy()
            self.velocity = np.asarray(velocity, dtype=np.float32).copy()
            self.servo_hz = float(servo_hz)

    def snapshot(self):
        with self.lock:
            return {
                "command": None if self.command is None else self.command.copy(),
                "qpos": None if self.qpos is None else self.qpos.copy(),
                "velocity": self.velocity.copy(),
                "servo_hz": float(self.servo_hz),
                "error": self.error,
            }

    def set_error(self, message):
        with self.lock:
            self.error = str(message)


def cpv_servo_worker(
    robot,
    command_filter,
    shared_state,
    start_event,
    stop_event,
    control_enabled,
    cpv_hz,
    target_timeout_s,
):
    """固定频率 CPV 发送线程，与 ACT 推理解耦。"""
    try:
        start_event.wait()
        if stop_event.is_set():
            return

        period = 1.0 / float(cpv_hz)
        next_tick = time.monotonic()
        last_tick = next_tick

        while not stop_event.is_set():
            now = time.monotonic()
            if now < next_tick:
                time.sleep(min(next_tick - now, 0.001))
                continue

            if now - next_tick > 2.0 * period:
                next_tick = now
            next_tick += period

            dt = max(1e-4, now - last_tick)
            last_tick = now

            target, target_stamp = shared_state.get_target()
            if target is None:
                continue

            if now - target_stamp > float(target_timeout_s):
                raise RuntimeError(
                    f"ACT target stale for {(now-target_stamp)*1000.0:.0f} ms "
                    f"> {target_timeout_s*1000.0:.0f} ms"
                )

            qpos = robot.get_qpos()
            if qpos is None:
                continue

            command, vel_cmd = command_filter.filter(target, qpos, dt)

            if control_enabled:
                robot.send_action(command)

            servo_hz = 1.0 / dt if dt > 0 else 0.0
            shared_state.update_servo(command, qpos, vel_cmd, servo_hz)

    except Exception as exc:
        shared_state.set_error(f"{type(exc).__name__}: {exc}")
        stop_event.set()
        if control_enabled:
            robot.emergency_stop()


